<?php

use App\Http\Middleware\AssignRequestId;
use App\Http\Middleware\RequirePermission;
use App\Http\Middleware\ResolveOrganizationContext;
use App\Http\Middleware\SanitizeRichText;
use App\Http\Middleware\SecurityHeaders;
use App\Http\Middleware\SetLocale;
use Illuminate\Auth\AuthenticationException;
use Illuminate\Auth\Access\AuthorizationException;
use Illuminate\Database\Eloquent\ModelNotFoundException;
use Illuminate\Foundation\Application;
use Illuminate\Foundation\Configuration\Exceptions;
use Illuminate\Foundation\Configuration\Middleware;
use Illuminate\Http\Request;
use Illuminate\Validation\ValidationException;
use Symfony\Component\HttpKernel\Exception\HttpExceptionInterface;

// NOTE: compare with the skeleton generated by your Laravel version; keep its structure if it differs.
return Application::configure(basePath: dirname(__DIR__))
    ->withRouting(
        web: __DIR__ . '/../routes/web.php',
        api: __DIR__ . '/../routes/api.php',
        commands: __DIR__ . '/../routes/console.php',
        health: '/up',
    )
    // Private channel authorisation for the SPA (cookie session). Added by Bundle 2.
    ->withBroadcasting(__DIR__ . '/../routes/channels.php', ['middleware' => ['web', 'auth']])
    ->withMiddleware(function (Middleware $middleware): void {
        // Behind a reverse proxy (production) set TRUSTED_PROXIES to its address(es), or * if the app is only reachable through it.
        if ($proxies = env('TRUSTED_PROXIES')) {
            $middleware->trustProxies(at: $proxies === '*' ? '*' : array_map('trim', explode(',', $proxies)));
        }
        $middleware->statefulApi();                       // Sanctum cookie/session auth for the SPA
        $middleware->api(prepend: [AssignRequestId::class]);
        $middleware->api(append: [SetLocale::class, SanitizeRichText::class, SecurityHeaders::class]);
        $middleware->alias([
            'org.context' => ResolveOrganizationContext::class,
            'perm' => RequirePermission::class,
        ]);
    })
    ->withExceptions(function (Exceptions $exceptions): void {
        // One predictable error envelope for the API: { error: { code, message, request_id, details } }
        $envelope = function (string $code, string $message, int $status, ?array $details = null, ?Request $r = null) {
            return response()->json(['error' => [
                'code' => $code, 'message' => $message,
                'request_id' => $r?->attributes->get('request_id'), 'details' => $details,
            ]], $status);
        };

        $exceptions->shouldRenderJsonWhen(fn (Request $r) => $r->is('api/*') || $r->expectsJson());

        $exceptions->render(fn (ValidationException $e, Request $r) =>
            $envelope('validation_failed', $e->getMessage(), 422, $e->errors(), $r));
        $exceptions->render(fn (AuthenticationException $e, Request $r) =>
            $envelope('unauthenticated', __('api.unauthenticated'), 401, null, $r));
        $exceptions->render(fn (AuthorizationException $e, Request $r) =>
            $envelope('forbidden', __('api.forbidden'), 403, null, $r));
        $exceptions->render(fn (ModelNotFoundException $e, Request $r) =>
            $envelope('not_found', __('api.not_found'), 404, null, $r));
        $exceptions->render(function (HttpExceptionInterface $e, Request $r) use ($envelope) {
            if (!$r->is('api/*')) return null;
            $status = $e->getStatusCode();
            $code = match ($status) { 403 => 'forbidden', 404 => 'not_found', 422 => 'unprocessable', 429 => 'too_many_requests', default => 'http_error' };
            $msg = $e->getMessage() && !in_array($e->getMessage(), ['forbidden', 'no_active_membership'], true)
                ? $e->getMessage() : ($status === 403 ? __('api.forbidden') : __('api.error'));
            return $envelope($code, $msg, $status, null, $r);
        });
    })->create();
